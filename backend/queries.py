FIND_CONNECTED_CLIENTS = """
SELECT DISTINCT
    P.HANDLE AS id,
    CAST(P.CODIGO AS varchar(50)) AS codigo,
    P.NOME AS nome,
    P.CGCCPF AS documento,
    P.K_NOMEGRUPO AS groupName,
    UF.SIGLA AS uf
FROM GN_PESSOAS P
LEFT JOIN ESTADOS UF ON UF.HANDLE = P.ESTADO
WHERE EXISTS (
    SELECT 1
    FROM GN_PESSOAS S
    WHERE S.HANDLE IN ({ids})
      AND (
        (
          LEN(REPLACE(REPLACE(REPLACE(ISNULL(S.CGCCPF, ''), '.', ''), '/', ''), '-', '')) >= 8
          AND LEFT(REPLACE(REPLACE(REPLACE(S.CGCCPF, '.', ''), '/', ''), '-', ''), 8)
              = LEFT(REPLACE(REPLACE(REPLACE(ISNULL(P.CGCCPF, ''), '.', ''), '/', ''), '-', ''), 8)
        )
        OR COALESCE(S.GRUPOEMPRESARIAL, S.HANDLE) = COALESCE(P.GRUPOEMPRESARIAL, P.HANDLE)
        OR (
          NULLIF(LTRIM(RTRIM(S.K_NOMEGRUPO)), '') IS NOT NULL
          AND LTRIM(RTRIM(S.K_NOMEGRUPO)) COLLATE Latin1_General_CI_AI
              = LTRIM(RTRIM(P.K_NOMEGRUPO)) COLLATE Latin1_General_CI_AI
        )
      )
)
ORDER BY nome, codigo
"""

SUMMARY = """
WITH Faturamento AS (
    SELECT
        DATEFROMPARTS(YEAR(A.DATAEMISSAO), MONTH(A.DATAEMISSAO), 1) AS mes,
        SUM(ITEM.VALORLIQUIDO + ITEM.SEGURO + ITEM.FRETE + ITEM.OUTROS) AS valor,
        SUM(ITEM.IPIVALOR + ITEM.ICMSVALOR + ITEM.VALORPIS + ITEM.VALORCOFINS) AS impostos,
        SUM(ITEM.QUANTIDADE) AS quantidade,
        COUNT(DISTINCT A.HANDLE) AS documentos
    FROM FN_DOCUMENTOS A
    JOIN CM_OPERACOESFATURAMENTO OFAT ON OFAT.HANDLE = A.OPERACAOFATURAMENTO
    JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = A.HANDLE
    JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
    JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
    WHERE A.PESSOA IN ({ids})
      AND A.DATAEMISSAO >= ? AND A.DATAEMISSAO < ?
      AND A.ENTRADASAIDA = 'S' AND A.ABRANGENCIA = 'A' AND A.FILIAL = 1
      AND A.TIPODOCUMENTO IN (23,64,72) AND A.NRNOTAFISCAL > 0
      AND A.STATUSNFE IN (6,4,1)
      AND (OFAT.K_TIPONATUREZAOPER = 1 OR OFAT.HANDLE IN (44,149))
      AND {category_filter}
    GROUP BY YEAR(A.DATAEMISSAO), MONTH(A.DATAEMISSAO)
),
Devolucoes AS (
    SELECT mes, SUM(valor) AS valor FROM (
        SELECT
            DATEFROMPARTS(YEAR(A.DATAEMISSAO), MONTH(A.DATAEMISSAO), 1) AS mes,
            SUM(ITEM.VALORLIQUIDO + ITEM.SEGURO + ITEM.FRETE + ITEM.OUTROS) AS valor
        FROM FN_DOCUMENTOS A
        JOIN CM_OPERACOESFATURAMENTO OFAT ON OFAT.HANDLE = A.OPERACAOFATURAMENTO AND OFAT.HANDLE <> 150
        JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = A.HANDLE
        JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
        JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
        WHERE A.PESSOA IN ({ids})
          AND A.DATAEMISSAO >= ? AND A.DATAEMISSAO < ?
          AND A.ABRANGENCIA = 'A' AND A.FILIAL = 1
          AND A.TIPODOCUMENTO = 24 AND A.NRNOTAFISCAL > 0
          AND A.STATUSNFE IN (6,4) AND OFAT.K_TIPONATUREZAOPER = 2
          AND {category_filter}
        GROUP BY YEAR(A.DATAEMISSAO), MONTH(A.DATAEMISSAO)
        UNION ALL
        SELECT
            DATEFROMPARTS(YEAR(NF.DATAENTRADA), MONTH(NF.DATAENTRADA), 1) AS mes,
            SUM(ITEM.TOTALGERAL) AS valor
        FROM FN_DOCUMENTOS NF
        JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = NF.HANDLE
        JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
        JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
        WHERE NF.PESSOA IN ({ids})
          AND NF.DATAENTRADA >= ? AND NF.DATAENTRADA < ?
          AND NF.ENTRADASAIDA IN ('E','I') AND NF.ABRANGENCIA = 'R'
          AND NF.TIPODEMOVIMENTO = 3
          AND {category_filter}
        GROUP BY YEAR(NF.DATAENTRADA), MONTH(NF.DATAENTRADA)
    ) X GROUP BY mes
),
Meses AS (
    SELECT mes FROM Faturamento UNION SELECT mes FROM Devolucoes
)
SELECT
    M.mes,
    COALESCE(F.valor,0) AS faturamento,
    COALESCE(D.valor,0) AS devolucoes,
    COALESCE(F.valor,0) - COALESCE(D.valor,0) AS liquido,
    COALESCE(F.impostos,0) AS impostos,
    COALESCE(F.quantidade,0) AS quantidade,
    COALESCE(F.documentos,0) AS documentos
FROM Meses M
LEFT JOIN Faturamento F ON F.mes = M.mes
LEFT JOIN Devolucoes D ON D.mes = M.mes
ORDER BY M.mes
"""

