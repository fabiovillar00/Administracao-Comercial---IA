FIND_CLIENTS = """
SELECT TOP (100)
    P.HANDLE AS id,
    CAST(P.CODIGO AS varchar(50)) AS codigo,
    P.NOME AS nome,
    P.CGCCPF AS documento,
    P.K_NOMEGRUPO AS groupName,
    UF.SIGLA AS uf
FROM GN_PESSOAS P
LEFT JOIN ESTADOS UF ON UF.HANDLE = P.ESTADO
WHERE P.NOME COLLATE Latin1_General_CI_AI LIKE ? COLLATE Latin1_General_CI_AI
   OR REPLACE(REPLACE(P.NOME, ' ', ''), '.', '') COLLATE Latin1_General_CI_AI LIKE REPLACE(REPLACE(?, ' ', ''), '.', '') COLLATE Latin1_General_CI_AI
   OR CAST(P.CODIGO AS varchar(50)) LIKE ?
   OR P.CGCCPF LIKE ?
ORDER BY CASE WHEN P.NOME = ? THEN 0 ELSE 1 END, P.NOME
"""

FIND_BUSINESS_GROUP = """
WITH Matriz AS (
    SELECT TOP (1) HANDLE, CODIGO, NOME
    FROM GN_PESSOAS
    WHERE CODIGO = ?
)
SELECT
    P.HANDLE AS id,
    CAST(P.CODIGO AS varchar(50)) AS codigo,
    P.NOME AS nome,
    P.CGCCPF AS documento,
    P.K_NOMEGRUPO AS groupName,
    UF.SIGLA AS uf
FROM GN_PESSOAS P
CROSS JOIN Matriz M
LEFT JOIN ESTADOS UF ON UF.HANDLE = P.ESTADO
WHERE P.HANDLE = M.HANDLE OR P.GRUPOEMPRESARIAL = M.HANDLE
ORDER BY CASE WHEN P.HANDLE = M.HANDLE THEN 0 ELSE 1 END, P.NOME
"""

