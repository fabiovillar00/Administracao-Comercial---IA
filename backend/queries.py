BRANCH_SUMMARY = """
WITH Faturamento AS (
    SELECT A.PESSOA,
        SUM(ITEM.VALORLIQUIDO + ITEM.SEGURO + ITEM.FRETE + ITEM.OUTROS) AS faturamento,
        SUM(ITEM.QUANTIDADE) AS quantidade,
        COUNT(DISTINCT A.HANDLE) AS documentos
    FROM FN_DOCUMENTOS A
    JOIN CM_OPERACOESFATURAMENTO OFAT ON OFAT.HANDLE = A.OPERACAOFATURAMENTO
    JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = A.HANDLE
    JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
    JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
    WHERE A.PESSOA IN ({ids}) AND A.DATAEMISSAO >= ? AND A.DATAEMISSAO < ?
      AND A.ENTRADASAIDA = 'S' AND A.ABRANGENCIA = 'A' AND A.FILIAL = 1
      AND A.TIPODOCUMENTO IN (23,64,72) AND A.NRNOTAFISCAL > 0
      AND A.STATUSNFE IN (6,4,1)
      AND (OFAT.K_TIPONATUREZAOPER = 1 OR OFAT.HANDLE IN (44,149))
      AND {category_filter}
    GROUP BY A.PESSOA
),
Devolucoes AS (
    SELECT PESSOA, SUM(valor) AS devolucoes FROM (
        SELECT A.PESSOA, SUM(ITEM.VALORLIQUIDO + ITEM.SEGURO + ITEM.FRETE + ITEM.OUTROS) AS valor
        FROM FN_DOCUMENTOS A
        JOIN CM_OPERACOESFATURAMENTO OFAT ON OFAT.HANDLE = A.OPERACAOFATURAMENTO AND OFAT.HANDLE <> 150
        JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = A.HANDLE
        JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
        JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
        WHERE A.PESSOA IN ({ids}) AND A.DATAEMISSAO >= ? AND A.DATAEMISSAO < ?
          AND A.ABRANGENCIA = 'A' AND A.FILIAL = 1 AND A.TIPODOCUMENTO = 24
          AND A.NRNOTAFISCAL > 0 AND A.STATUSNFE IN (6,4) AND OFAT.K_TIPONATUREZAOPER = 2
          AND {category_filter}
        GROUP BY A.PESSOA
        UNION ALL
        SELECT NF.PESSOA, SUM(ITEM.TOTALGERAL) AS valor
        FROM FN_DOCUMENTOS NF
        JOIN CM_ITENS ITEM ON ITEM.DOCUMENTO = NF.HANDLE
        JOIN PD_PRODUTOS PROD ON PROD.HANDLE = ITEM.PRODUTO
        JOIN PD_FAMILIASPRODUTOS FAM ON FAM.HANDLE = PROD.FAMILIA
        WHERE NF.PESSOA IN ({ids}) AND NF.DATAENTRADA >= ? AND NF.DATAENTRADA < ?
          AND NF.ENTRADASAIDA IN ('E','I') AND NF.ABRANGENCIA = 'R' AND NF.TIPODEMOVIMENTO = 3
          AND {category_filter}
        GROUP BY NF.PESSOA
    ) X GROUP BY PESSOA
)
SELECT P.HANDLE AS id, CAST(P.CODIGO AS varchar(50)) AS codigo, P.NOME AS nome, P.CGCCPF AS documento, UF.SIGLA AS uf,
    COALESCE(F.faturamento,0) AS faturamento, COALESCE(D.devolucoes,0) AS devolucoes,
    COALESCE(F.faturamento,0) - COALESCE(D.devolucoes,0) AS liquido,
    COALESCE(F.quantidade,0) AS quantidade, COALESCE(F.documentos,0) AS documentos
FROM GN_PESSOAS P
LEFT JOIN ESTADOS UF ON UF.HANDLE = P.ESTADO
LEFT JOIN Faturamento F ON F.PESSOA = P.HANDLE
LEFT JOIN Devolucoes D ON D.PESSOA = P.HANDLE
WHERE P.HANDLE IN ({ids})
ORDER BY liquido DESC, P.NOME
"""
